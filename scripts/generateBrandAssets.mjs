import { readFileSync, writeFileSync } from 'node:fs';
import { BRAND_COLOR, BRAND_REVISION, HANGER_PATH } from '../client/src/branding/identity.mjs';

const publicRoot = new URL('../client/public/', import.meta.url);
const stroke = `fill="none" stroke-linecap="round" stroke-linejoin="round"`;
const mark = color => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" ${stroke} stroke-width="5.4" stroke="${color}"><path d="${HANGER_PATH}"/></svg>\n`;
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="16" fill="${BRAND_COLOR}"/><path d="${HANGER_PATH}" transform="translate(3.2 3.2) scale(.9)" ${stroke} stroke-width="6" stroke="white"/></svg>\n`;
const write = (path, value) => writeFileSync(new URL(path, publicRoot), value);
write('images/laundry/brand-mark.svg', mark(BRAND_COLOR));
write('images/laundry/brand-mark-white.svg', mark('#ffffff'));
write('images/laundry/brand-mark-ink.svg', mark('#080f31'));
write('images/laundry/brand-favicon.svg', icon);
write('favicon.svg', icon);

const lettering = JSON.parse(readFileSync(new URL('../client/src/branding/wordmark.json', import.meta.url), 'utf8'));
for (const reverse of [false, true]) {
  const colors = reverse ? { ink: '#ffffff', accent: '#ffffff' } : { ink: '#080f31', accent: BRAND_COLOR };
  const logo = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${lettering.width} 64" role="img" aria-label="IndoDhobi"><path d="${HANGER_PATH}" ${stroke} stroke-width="5.4" stroke="${colors.accent}"/>${lettering.paths.map(path => `<path d="${path.d}" fill="${colors[path.color]}"/>`).join('')}</svg>\n`;
  write(`images/laundry/brand-logo${reverse ? '-white' : ''}.svg`, logo);
}

// The pre-JavaScript loader uses the same master geometry as the React loader.
const indexPath = new URL('../client/index.html', import.meta.url);
let html = readFileSync(indexPath, 'utf8');
const loader = `      <!-- brand-loader:start — generated by npm run brand:generate -->
      <div class="id-loader id-loader--screen" role="status" aria-live="polite">
        <div class="id-loader__stage" aria-hidden="true">
          <svg class="id-loader__mark" viewBox="0 0 64 64" ${stroke} stroke-width="5.4" stroke="currentColor">
            <path class="id-loader__outline" d="${HANGER_PATH}"></path>
            <path class="id-loader__trace" d="${HANGER_PATH}" pathLength="1"></path>
          </svg>
        </div>
        <div class="id-loader__copy">
          <p class="id-loader__brand">Indo<span>Dhobi</span></p>
          <p class="id-loader__label">Preparing your fresh load</p>
        </div>
        <div class="id-loader__progress" aria-hidden="true"><span></span></div>
      </div>
      <!-- brand-loader:end -->`;
html = html.replace(/      <!-- brand-loader:start[\s\S]*?<!-- brand-loader:end -->/, loader);
html = html.replace(/brand=hanger-[\w-]+/g, `brand=${BRAND_REVISION}`);
writeFileSync(indexPath, html);
console.log('Updated logo SVGs, favicon SVGs, and startup loader from the master geometry.');
